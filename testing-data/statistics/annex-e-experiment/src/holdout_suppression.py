# ------------------------------------------------------------------ CONFIG
EXPERIMENT_ID = "EXP-ONB-RECOVERY-001"
SECRET = b"demo-secret-change-me"       # that su: secret manager, KHONG commit len git
ALGORITHM_VERSION = "hmac-sha256-v2"
BUCKETS = 10_000
DEFAULT_TREATMENT_BP = 5_000            # 50/50 (bp = 1/10000). 90/10 -> 9000. Dong bang khi bat dau thi nghiem.

# Ly do chan (suppression reason). Chi la du lieu ghi them, khong sua/xoa.
REASONS = (
    "OPT_OUT",            # khach tu choi nhan tin (REC 05, Nghi dinh 91/2020)
    "COMPLAINT",          # khieu nai
    "COMPLETED",          # da mo tai khoan / hoan thanh ho so (thay cho "da mua hang")
    "DO_NOT_CONTACT",     # yeu cau cua ngan hang / phap ly
    "REVIEW_PENDING",     # so dien thoai dung chung, cho ra soat (EVT 05)
)

DDL = """
CREATE TABLE IF NOT EXISTS experiment_assignment (
    assignment_id        INTEGER PRIMARY KEY AUTOINCREMENT,
    experiment_id        TEXT NOT NULL,
    applicant_key        TEXT NOT NULL,
    arm                  TEXT NOT NULL CHECK (arm IN ('TREATMENT','CONTROL')),
    index_application_id TEXT NOT NULL,
    hash_bucket          INTEGER NOT NULL,
    treatment_share_bp   INTEGER NOT NULL,
    assigned_at          TEXT NOT NULL,
    algorithm_version    TEXT NOT NULL,
    UNIQUE (experiment_id, applicant_key)
);
CREATE TABLE IF NOT EXISTS suppression_list (
    suppression_id INTEGER PRIMARY KEY AUTOINCREMENT,
    applicant_key  TEXT NOT NULL,
    reason         TEXT NOT NULL CHECK (reason IN ('OPT_OUT','COMPLAINT','COMPLETED','DO_NOT_CONTACT','REVIEW_PENDING')),
    source         TEXT NOT NULL,          -- he thong nguon: sms_stop, bank_core, staff, ...
    effective_at   TEXT NOT NULL,          -- co hieu luc tu thoi diem nay
    created_at     TEXT NOT NULL,
    UNIQUE (applicant_key, reason)
);
CREATE TABLE IF NOT EXISTS dispatch_decision_log (
    log_id        INTEGER PRIMARY KEY AUTOINCREMENT,
    applicant_key TEXT NOT NULL,
    arm           TEXT,
    allowed       INTEGER NOT NULL,
    reason        TEXT NOT NULL,
    decided_at    TEXT NOT NULL
);
"""


def connect(path: str) -> sqlite3.Connection:
    conn = sqlite3.connect(path, timeout=30, check_same_thread=False)
    conn.executescript(DDL)
    return conn


def _now_iso(now=None):
    return (now or datetime.now()).isoformat(timespec="seconds")


# ============================================================ 1. HOLDOUT GROUP
def hash_bucket(applicant_key: str, experiment_id: str = EXPERIMENT_ID, secret: bytes = SECRET) -> int:
    msg = f"{experiment_id}|{applicant_key}".encode()
    digest = hmac.new(secret, msg, hashlib.sha256).digest()
    return int.from_bytes(digest[:8], "big") % BUCKETS


def arm_from_bucket(bucket: int, treatment_bp: int = DEFAULT_TREATMENT_BP) -> str:
    """bucket < treatment_bp -> TREATMENT (nhan tin); con lai -> CONTROL (holdout, khong nhan tin)."""
    return "TREATMENT" if bucket < treatment_bp else "CONTROL"


def assign(conn, applicant_key, application_id, eligible, now=None, treatment_bp=DEFAULT_TREATMENT_BP):
    """
    Chia nhom mot lan duy nhat cho moi nguoi.
    Tra ve dict hoac None (khong du dieu kien / dang bi chan truoc khi chia).
    - Nguoi da nam trong suppression list tai thoi diem chia nhom -> khong chia (loai ra khoi thi nghiem,
      doi xung cho ca hai nhom vi quyet dinh nay chua dung toi nhom).
    - Da co dong dang ky -> tra lai dong cu (nhom, index application khong doi), bo qua treatment_bp moi.
    """
    if not eligible:
        return None
    now = now or datetime.now()
    existing = _get_assignment(conn, applicant_key)
    if existing is None and active_suppressions(conn, applicant_key, now):
        return None
    b = hash_bucket(applicant_key)
    conn.execute(
        """INSERT OR IGNORE INTO experiment_assignment
           (experiment_id, applicant_key, arm, index_application_id, hash_bucket,
            treatment_share_bp, assigned_at, algorithm_version)
           VALUES (?,?,?,?,?,?,?,?)""",
        (EXPERIMENT_ID, applicant_key, arm_from_bucket(b, treatment_bp), application_id, b,
         treatment_bp, _now_iso(now), ALGORITHM_VERSION),
    )
    conn.commit()
    return _get_assignment(conn, applicant_key)


def _get_assignment(conn, applicant_key):
    row = conn.execute(
        """SELECT arm, index_application_id, hash_bucket, treatment_share_bp, assigned_at
           FROM experiment_assignment WHERE experiment_id=? AND applicant_key=?""",
        (EXPERIMENT_ID, applicant_key),
    ).fetchone()
    if row is None:
        return None
    return dict(arm=row[0], index_application_id=row[1], hash_bucket=row[2],
                treatment_share_bp=row[3], assigned_at=row[4])


# ======================================================== 2. SUPPRESSION LIST
def add_suppression(conn, applicant_key, reason, source, effective_at=None, now=None):
    """
    Them mot ly do chan. Ghi them, khong sua/xoa; goi lap lai khong tao dong trung (UNIQUE).
    Tra ve True neu la dong moi, False neu da ton tai.
    """
    if reason not in REASONS:
        raise ValueError(f"reason khong hop le: {reason}")
    now = now or datetime.now()
    cur = conn.execute(
        """INSERT OR IGNORE INTO suppression_list
           (applicant_key, reason, source, effective_at, created_at) VALUES (?,?,?,?,?)""",
        (applicant_key, reason, source, _now_iso(effective_at or now), _now_iso(now)),
    )
    conn.commit()
    return cur.rowcount == 1


def active_suppressions(conn, applicant_key, at=None):
    """Danh sach ly do chan dang co hieu luc tai thoi diem `at`."""
    at = at or datetime.now()
    rows = conn.execute(
        "SELECT reason FROM suppression_list WHERE applicant_key=? AND effective_at<=?",
        (applicant_key, _now_iso(at)),
    ).fetchall()
    return [r[0] for r in rows]


# ==================================================== 3. CONG DISPATCH (BACKEND)
def check_before_send(conn, applicant_key, now=None):
    """
    Ham Backend goi NGAY TRUOC moi lan gui nhac nho thu nghiem (REC 06).
    Tra ve (allowed: bool, reason: str). Dong vai tro MOT trong cac cong; Treatment van phai qua cac cong khac
    (trang thai ho so, quyen lien he, gio yen lang, ngan sach, phien ban chien dich).

    Thu tu kiem tra:
      1. Khong co dong dang ky      -> chan (chua chia nhom)
      2. arm = CONTROL (holdout)    -> chan
      3. Co ly do chan hieu luc     -> chan (kem ly do)
      4. Con lai                    -> cho di tiep
    Loi bat ky (DB loi, du lieu hong) -> chan (fail closed), khong bao gio mac dinh la cho gui.
    """
    now = now or datetime.now()
    arm = None
    try:
        a = _get_assignment(conn, applicant_key)
        if a is None:
            allowed, reason = False, "BLOCK_NOT_ASSIGNED"
        else:
            arm = a["arm"]
            if arm != "TREATMENT":
                allowed, reason = False, "BLOCK_CONTROL_HOLDOUT"
            else:
                sup = active_suppressions(conn, applicant_key, now)
                if sup:
                    allowed, reason = False, "BLOCK_SUPPRESSED:" + ",".join(sorted(sup))
                else:
                    allowed, reason = True, "ALLOW_PASS_TO_NEXT_GATES"
    except Exception as exc:                      # fail closed
        return False, f"BLOCK_ERROR:{type(exc).__name__}"
    try:
        conn.execute(
            "INSERT INTO dispatch_decision_log (applicant_key, arm, allowed, reason, decided_at) VALUES (?,?,?,?,?)",
            (applicant_key, arm, int(allowed), reason, _now_iso(now)),
        )
        conn.commit()
    except Exception:
        pass                                      # loi ghi log khong duoc lam doi quyet dinh chan
    return allowed, reason


