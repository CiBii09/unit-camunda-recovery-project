def chi2_p_value(chi2):
    return math.erfc(math.sqrt(chi2 / 2))


def _fresh():
    return connect(os.path.join(tempfile.mkdtemp(), "demo.db"))


def run_tests():
    t0 = datetime(2026, 11, 12, 9, 0, 0)
    results = []

    def check(name, cond, detail=""):
        print(f"TEST {len(results)+1} - {name}\n  {'PASS' if cond else 'FAIL'} {detail}")
        results.append(cond)

    # 1. Holdout 50/50 va 90/10 dung ty le (kiem dinh chi binh phuong, p >= 0,001)
    for bp, label in ((5000, "50/50"), (9000, "90/10")):
        n = 100_000
        t = sum(arm_from_bucket(hash_bucket(f"APL-{i:06d}"), bp) == "TREATMENT" for i in range(n))
        exp = n * bp / BUCKETS
        chi2 = (t - exp) ** 2 / exp + ((n - t) - (n - exp)) ** 2 / (n - exp)
        p = chi2_p_value(chi2)
        check(f"Ty le chia {label} tren 100.000 nguoi", p >= 0.001, f"(Treatment {t}, ky vong {exp:.0f}, p = {p:.3f})")

    # 2. Doi ty le sau khi da chia: nguoi cu giu nhom cu
    conn = _fresh()
    a1 = assign(conn, "APL-1", "APP-1", True, t0, treatment_bp=5000)
    a2 = assign(conn, "APL-1", "APP-2", True, t0 + timedelta(days=1), treatment_bp=9000)
    n_rows = conn.execute("SELECT COUNT(*) FROM experiment_assignment").fetchone()[0]
    check("Doi ty le giua chung: nguoi da chia giu nguyen nhom", a1 == a2 and n_rows == 1)

    # 3. Khong chia nhom khi khong du dieu kien
    conn = _fresh()
    check("Khong du dieu kien -> khong chia nhom", assign(conn, "APL-2", "APP-1", False, t0) is None)

    # 4. Da co ly do chan truoc khi chia -> khong chia
    conn = _fresh()
    add_suppression(conn, "APL-3", "COMPLETED", "bank_core", now=t0 - timedelta(days=1))
    check("Da hoan thanh ho so truoc khi chia -> khong chia nhom", assign(conn, "APL-3", "APP-1", True, t0) is None)

    # Tim hai nguoi thuoc Treatment va Control (theo 50/50) de test cong
    keys = [f"APL-T{i}" for i in range(200)]
    tkey = next(k for k in keys if arm_from_bucket(hash_bucket(k)) == "TREATMENT")
    ckey = next(k for k in keys if arm_from_bucket(hash_bucket(k)) == "CONTROL")

    # 5. Cong: Treatment sach -> cho di tiep; Control -> chan; chua chia -> chan
    conn = _fresh()
    assign(conn, tkey, "APP-1", True, t0)
    assign(conn, ckey, "APP-1", True, t0)
    ok_t = check_before_send(conn, tkey, t0)
    ok_c = check_before_send(conn, ckey, t0)
    ok_n = check_before_send(conn, "APL-CHUA-CHIA", t0)
    check("Cong dispatch: Treatment cho qua, Control va chua chia bi chan",
          ok_t == (True, "ALLOW_PASS_TO_NEXT_GATES") and ok_c == (False, "BLOCK_CONTROL_HOLDOUT")
          and ok_n == (False, "BLOCK_NOT_ASSIGNED"))

    # 6. Opt-out SAU khi chia: van chan gui, nhung giu nhom (ITT)
    conn = _fresh()
    assign(conn, tkey, "APP-1", True, t0)
    add_suppression(conn, tkey, "OPT_OUT", "sms_stop", now=t0 + timedelta(days=2))
    allowed, reason = check_before_send(conn, tkey, t0 + timedelta(days=3))
    still = _get_assignment(conn, tkey)
    check("Opt-out sau khi chia: chan gui, giu nguyen nhom (ITT)",
          not allowed and reason == "BLOCK_SUPPRESSED:OPT_OUT" and still["arm"] == "TREATMENT")

    # 7. Them ly do chan giua luc chia nhom va luc gui -> cong phai thay
    conn = _fresh()
    assign(conn, tkey, "APP-1", True, t0)
    before = check_before_send(conn, tkey, t0 + timedelta(minutes=1))
    add_suppression(conn, tkey, "COMPLAINT", "staff", now=t0 + timedelta(minutes=2))
    after = check_before_send(conn, tkey, t0 + timedelta(minutes=3))
    check("Kiem tra tai thoi diem gui (khong dung ket qua cu)", before[0] and not after[0])

    # 8. Ly do chan co hieu luc trong tuong lai chua chan
    conn = _fresh()
    assign(conn, tkey, "APP-1", True, t0)
    add_suppression(conn, tkey, "DO_NOT_CONTACT", "bank", effective_at=t0 + timedelta(days=5), now=t0)
    now_ok = check_before_send(conn, tkey, t0 + timedelta(days=1))[0]
    later = check_before_send(conn, tkey, t0 + timedelta(days=6))[0]
    check("effective_at trong tuong lai: chua chan, den han thi chan", now_ok and not later)

    # 9. Goi lap them cung ly do khong tao dong trung; ly do la la bi tu choi
    conn = _fresh()
    first = add_suppression(conn, "APL-9", "OPT_OUT", "sms_stop", now=t0)
    second = add_suppression(conn, "APL-9", "OPT_OUT", "sms_stop", now=t0 + timedelta(hours=1))
    rows = conn.execute("SELECT COUNT(*) FROM suppression_list").fetchone()[0]
    try:
        add_suppression(conn, "APL-9", "BUY_ALREADY", "x")
        bad = False
    except ValueError:
        bad = True
    check("Them lap khong trung dong; ly do la bi tu choi", first and not second and rows == 1 and bad)

    # 10. Nhieu ly do cung luc deu duoc ghi trong ly do chan
    conn = _fresh()
    assign(conn, tkey, "APP-1", True, t0)
    add_suppression(conn, tkey, "OPT_OUT", "sms_stop", now=t0)
    add_suppression(conn, tkey, "COMPLETED", "bank_core", now=t0)
    allowed, reason = check_before_send(conn, tkey, t0 + timedelta(hours=1))
    check("Nhieu ly do chan: tra ve du ca hai", (not allowed) and reason == "BLOCK_SUPPRESSED:COMPLETED,OPT_OUT")

    # 11. Fail closed: loi DB -> chan, khong bao gio cho gui
    conn = _fresh()
    assign(conn, tkey, "APP-1", True, t0)
    conn.close()
    allowed, reason = check_before_send(conn, tkey, t0)
    check("Loi co so du lieu -> chan (fail closed)", (not allowed) and reason.startswith("BLOCK_ERROR"))

    # 12. 50 luong dong thoi chia cung mot nguoi -> 1 dong, 1 nhom
    path = os.path.join(tempfile.mkdtemp(), "conc.db")
    connect(path).close()
    out = []

    def worker():
        c = connect(path)
        out.append(assign(c, "APL-CONC", "APP-1", True, t0)["arm"])
        c.close()

    threads = [threading.Thread(target=worker) for _ in range(50)]
    [t.start() for t in threads]
    [t.join() for t in threads]
    rows = connect(path).execute("SELECT COUNT(*) FROM experiment_assignment").fetchone()[0]
    check("50 luong dong thoi: 1 dong, 1 nhom", rows == 1 and len(set(out)) == 1)

    # 13. Moi quyet dinh cong deu duoc ghi log (DAT 03, SEC 04)
    conn = _fresh()
    assign(conn, tkey, "APP-1", True, t0)
    assign(conn, ckey, "APP-1", True, t0)
    check_before_send(conn, tkey, t0)
    check_before_send(conn, ckey, t0)
    n_log = conn.execute("SELECT COUNT(*) FROM dispatch_decision_log").fetchone()[0]
    check("Moi quyet dinh cong duoc ghi log", n_log == 2)

    print("\n=> TAT CA TEST DAT" if all(results) else "\n=> CO TEST THAT BAI")
    return all(results)


if __name__ == "__main__":
    # Do not raise SystemExit inside an interactive Jupyter/Colab environment
    run_tests()